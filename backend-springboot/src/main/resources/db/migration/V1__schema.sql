-- Revaluation workflow schema (PostgreSQL; also runs on H2 in PostgreSQL mode for tests)

create sequence request_seq start with 1;

create table app_user (
  username         varchar(64)  primary key,
  display_name     varchar(120) not null,
  email            varchar(160) not null,
  role             varchar(20)  not null,
  department       varchar(20),
  candidate_groups varchar(200)
);

create table exam_session (
  code                varchar(20)  primary key,
  name                varchar(80)  not null,
  result_published_on date         not null
);

create table subject_catalog (
  code             varchar(20)  primary key,
  name             varchar(120) not null,
  department       varchar(20)  not null,
  max_marks        integer      not null,
  script_available boolean      not null default true,
  first_evaluator  varchar(64)  references app_user(username)
);

create table revaluation_request (
  id                    varchar(20)  primary key,
  student_id            varchar(64)  not null references app_user(username),
  exam_session          varchar(20)  not null references exam_session(code),
  result_published_on   date         not null,
  status                varchar(30)  not null,
  process_instance_key  bigint,
  fee_per_subject_paise integer      not null,
  total_fee_paise       integer      not null,
  rejection_reason      varchar(500),
  created_at            timestamp with time zone not null,
  updated_at            timestamp with time zone not null
);
create index idx_request_student on revaluation_request(student_id);

create table request_subject (
  id             bigint generated by default as identity primary key,
  request_id     varchar(20)  not null references revaluation_request(id) on delete cascade,
  subject_code   varchar(20)  not null references subject_catalog(code),
  subject_name   varchar(120) not null,
  department     varchar(20)  not null,
  original_marks integer      not null,
  max_marks      integer      not null,
  revised_marks  integer,
  outcome        varchar(20),
  examiner_id    varchar(64)  references app_user(username),
  script_id      varchar(40),
  stage          varchar(200),
  unique (request_id, subject_code)
);

create table payment (
  id                  bigint generated by default as identity primary key,
  request_id          varchar(20)  not null references revaluation_request(id) on delete cascade,
  razorpay_order_id   varchar(60),
  razorpay_payment_id varchar(60),
  status              varchar(20)  not null,
  amount_paise        integer      not null,
  failure_reason      varchar(200),
  created_at          timestamp with time zone not null
);

create table request_event (
  id          bigint generated by default as identity primary key,
  request_id  varchar(20)  not null references revaluation_request(id) on delete cascade,
  occurred_at timestamp with time zone not null,
  message     varchar(500) not null
);
create index idx_event_request on request_event(request_id);
